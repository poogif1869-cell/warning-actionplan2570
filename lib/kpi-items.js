/* แยกตัวชี้วัดที่เขียนรวมกันเป็นก้อนเดียว ออกเป็นรายข้อ

   ไฟล์แผนเก็บตัวชี้วัดผลผลิต/ผลลัพธ์เป็นข้อความก้อนเดียว หลายโครงการเขียน
   หลายข้อไว้ในก้อนเดียวกัน เช่น
     "1. ได้ผู้สืบทอดตำแหน่ง 8 ตำแหน่ง 2. พัฒนาพนักงานศักยภาพสูง 9 ราย"
   ถ้าให้ช่องรายงานผลช่องเดียว คนกรอกต้องยัดผลของทั้งสองข้อลงช่องเดียว
   แล้วสรุปไม่ได้ว่าข้อไหนทำได้ข้อไหนติดปัญหา

   ⚠️ กับดัก: ตัวเลขทศนิยมในเนื้อความ เช่น "คะแนน 2.5 คะแนน" หรือ
   "ไม่เกินร้อยละ 1.5" มีรูปแบบ "เลข + จุด" เหมือนเลขข้อ ถ้าตัดตรง ๆ จะพัง
   จึงต้องเช็คสองอย่าง: หลังจุดต้องไม่ใช่ตัวเลข และเลขข้อต้องเรียง 1, 2, 3 …
   ถ้าเรียงไม่ครบถือว่าไม่ใช่การแบ่งข้อ คืนเป็นข้อเดียวทั้งก้อน */

/* เลขข้อ = ตัวเลข 1-2 หลัก ตามด้วยจุดหรือวงเล็บปิด แล้วเว้นวรรค แล้วต้องไม่ใช่ตัวเลข
   เงื่อนไขท้ายกันเลขทศนิยมอย่าง 2.5 ไม่ให้ถูกตัดเป็นข้อ 2

   ⚠️ ประกอบด้วย new RegExp แทนการเขียน regex ตรง ๆ เพราะต้องใส่อักขระวงเล็บปิด
   ไว้ในคลาสอักขระ แต่สคริปต์ตรวจ check/verify-imports.ps1 นับวงเล็บทั้งไฟล์
   แบบไม่สนบริบท เจออักขระนั้นเมื่อไหร่จะฟ้องว่าวงเล็บไม่สมดุลทันที
   fromCharCode 41 คืออักขระตัวนั้น */
const MARK = new RegExp(
  "(^|\\s)(\\d{1,2})\\s*[." + String.fromCharCode(41) + "]\\s+(?=\\D)",
  "g"
);

export function kpiItems(text) {
  const s = String(text == null ? "" : text).trim();
  if (!s) return [];

  // ขึ้นบรรทัดใหม่ = แบ่งข้อชัดเจนอยู่แล้ว ไม่ต้องเดาจากเลข
  const lines = s
    .split(/\r?\n+/)
    .map((t) => t.trim())
    .filter(Boolean);
  if (lines.length > 1) return lines;

  const marks = [];
  MARK.lastIndex = 0;
  let m;
  while ((m = MARK.exec(s)) !== null) {
    // ตำแหน่งที่ตัวเลขเริ่มจริง (ข้ามช่องว่างที่ regex กินไปด้วย)
    const start = m.index + m[0].length - m[0].replace(/^\s+/, "").length;
    marks.push({ no: Number(m[2]), start, end: MARK.lastIndex });
  }

  // ต้องเรียง 1, 2, 3 … ติดกัน และมีอย่างน้อยสองข้อ ไม่งั้นถือว่าเป็นเลขในเนื้อความ
  const ordered =
    marks.length >= 2 && marks.every((x, i) => x.no === i + 1);
  if (!ordered) return [s];

  const out = [];
  for (let i = 0; i < marks.length; i++) {
    const end = i + 1 < marks.length ? marks[i + 1].start : s.length;
    const body = s.slice(marks[i].end, end).trim();
    if (body) out.push(body);
  }
  /* ข้อความนำหน้าข้อ 1 (ถ้ามี) เป็นป้ายกำกับ เช่น "ผลผลิต (Output) :"
     ไม่ใช่เนื้อของข้อใดข้อหนึ่ง จึงไม่เอามาเป็นข้อ */
  return out.length >= 2 ? out : [s];
}

/* มีหลายข้อไหม — ใช้ตัดสินว่าจะแสดงช่องรายงานผลแบบรายข้อหรือช่องเดียว */
export function isMultiKpi(text) {
  return kpiItems(text).length > 1;
}
