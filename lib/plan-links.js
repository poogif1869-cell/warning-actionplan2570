/* ---------------------------------------------------------------------
   กรองตัวเลือกให้เหลือเฉพาะที่อยู่ใต้ตัวที่เลือกไว้ชั้นบน

   เลขนำหน้าเป็นตัวบอกสายพันธุ์ในตัวเอง:
     ยุทธศาสตร์ชาติที่ 2  ->  เป้าหมาย 2.x  ->  ประเด็น 2.x
     ประเด็นแผนแม่บท 03   ->  เป้าหมาย 3.x  ->  แผนย่อย 3.x  ->  เป้าหมายย่อย 3.x.x

   จึงกรองด้วยเลขนำหน้าได้เลย ไม่ต้องเก็บตารางแม่-ลูกเพิ่ม
   ถ้าเลขของตัวแม่อ่านไม่ออก ให้คืนทั้งหมด — ดีกว่าคืนว่างจนเลือกอะไรไม่ได้
   --------------------------------------------------------------------- */
export function leadNo(text) {
  const m = String(text || "").match(/(\d+)/);
  return m ? m[1].replace(/^0+/, "") || "0" : "";
}

export function underNo(list, no) {
  if (!no) return list;
  const hit = list.filter((v) => leadNo(v) === no);
  return hit.length ? hit : list;
}
