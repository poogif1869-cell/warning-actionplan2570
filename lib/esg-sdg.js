/* การเชื่อมโยงของโครงการหนึ่ง
   saved = แถวจากตาราง project_esg (ถ้ามี) — ถือเป็นของจริงทับข้อเสนอเสมอ
   คืน source: "ยืนยันแล้ว" | "แก้ไขแล้ว" | "ข้อเสนอ" | "ยังไม่มี" */
export function esgOf(uid, saved) {
  const base = PROPOSED.items[uid] || null;

  if (saved) {
    return {
      esg: saved.esg || [],
      sdg: saved.sdg || [],
      why: saved.note || (base ? base.why : ""),
      source: saved.confirmed ? "ยืนยันแล้ว" : "แก้ไขแล้ว",
      confirmed: Boolean(saved.confirmed),
      updatedBy: saved.updated_by || "",
      updatedAt: saved.updated_at || "",
    };
  }

  if (base) {
    return {
      esg: base.esg || [],
      sdg: base.sdg || [],
      why: base.why || "",
      /* วิเคราะห์จากอะไร — "ฝยศ.1" คืออ่านจากเอกสารคำของบประมาณจริง
         "แผน" คือโครงการที่ยังไม่มีเอกสาร ใช้ชื่อกับตัวชี้วัดในไฟล์แผนแทน */
      basis: base.basis || "แผน",
      source: "ข้อเสนอ",
      confirmed: false,
      updatedBy: "",
      updatedAt: "",
    };
  }

  /* โครงการที่เพิ่มเข้ามาใหม่หลังจากทำข้อเสนอชุดนี้ จะยังไม่มีทั้งสองทาง
     ไม่ใช่ข้อผิดพลาด — ให้เจ้าหน้าที่เลือกเองที่หน้าแก้ไขแผน */
  return { esg: [], sdg: [], why: "", source: "ยังไม่มี", confirmed: false, updatedBy: "", updatedAt: "" };
}

/* จำนวนโครงการที่มีข้อเสนอ ใช้บอกความครอบคลุมในหน้าเว็บ */
export function proposedCount() {
  return Object.keys(PROPOSED.items).length;
}
