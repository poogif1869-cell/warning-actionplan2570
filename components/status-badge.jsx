"use client";

/* =====================================================================
   ป้ายสถานะ — ใช้ให้เหมือนกันทุกที่ที่พูดถึงสถานะโครงการ

   เดิมสถานะเขียนเป็นข้อความต่อท้ายรหัสโครงการ ("010101 · ล่าช้า")
   อ่านผ่าน ๆ ไม่เห็น เพราะเป็นตัวสีเทาขนาดเดียวกับทุกอย่างรอบตัว
   ทำเป็นป้ายมีสีแล้วกวาดตาทีเดียวรู้ว่าโครงการไหนมีปัญหา

   สีผูกกับความหมาย ไม่ใช่ผูกกับลำดับ:
     แล้วเสร็จ        เขียว
     กำลังดำเนินการ   น้ำเงิน (กำลังไปได้ ไม่ใช่ทั้งดีทั้งแย่)
     ล่าช้า           แดง
     ยกเลิก           แดงจาง
     ยังไม่เริ่ม/ว่าง  เทา
   ===================================================================== */

const TONE = {
  "แล้วเสร็จ": "ok",
  "กำลังดำเนินการ": "info",
  "ล่าช้า": "bad",
  "ยกเลิก": "off",
  "ยังไม่เริ่ม": "none",
};

export default function StatusBadge({ status }) {
  const s = String(status || "").trim();
  if (!s) return <span className="pill none">ยังไม่ระบุสถานะ</span>;
  return <span className={"pill " + (TONE[s] || "none")}>{s}</span>;
}

/* ป้ายความคืบหน้าการรายงานผล — "รายงานแล้ว 5/12"
   nPlanned = 0 แปลว่าโครงการนี้ไม่มีแผนรายเดือน จึงไม่มีตัวหารให้เทียบ
   ต้องเขียนต่างออกไป ไม่ใช่โชว์ 0/0 ซึ่งอ่านเหมือนยังไม่ได้ทำอะไรเลย */
export function ReportBadge({ done, planned }) {
  const d = Number(done) || 0;
  const p = Number(planned) || 0;

  if (!p) {
    return (
      <span className={"pill " + (d ? "ok" : "none")}>
        {d ? "รายงานแล้ว " + d + " เดือน" : "ไม่มีแผนรายเดือน"}
      </span>
    );
  }

  const tone = d >= p ? "ok" : d > 0 ? "warn" : "none";
  return (
    <span className={"pill " + tone}>
      {d}/{p} เดือน
    </span>
  );
}
